def icon(name: str, size: int = 18, color: str = "currentColor", stroke_width: float = 2.0) -> str:
    """Return an inline `<svg>` string for the named Lucide icon.

    Use inside `st.markdown(..., unsafe_allow_html=True)`. Inherits text colour
    by default; pass `color="#0A2540"` for explicit ink.
    """
    body = _PATHS.get(name)
    if not body:
        return ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round" '
        f'style="display:inline-block; vertical-align:-3px; margin-right:6px;">{body}</svg>'
    )


def icon_label(name: str, label: str, size: int = 18, color: str = "currentColor") -> str:
    """Convenience: SVG + label inline. For markdown injection."""
    return icon(name, size, color) + label
